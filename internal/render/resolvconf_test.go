package render

import (
	"testing"

	"github.com/abundo/portitor/internal/fwconfig"
)

func TestResolvConf(t *testing.T) {
	lease := map[string][]string{"wan0": {"192.0.2.9", "192.0.2.8"}}
	gen := "# Generated by portitor-agent. Do not edit.\n"
	for _, tc := range []struct {
		name string
		r    *fwconfig.Resolver
		dhcp map[string][]string
		want string
		ok   bool
	}{
		{"unmanaged", nil, lease, "", false},
		{"static", &fwconfig.Resolver{Servers: []string{"1.1.1.1", "2606:4700:4700::1111"}}, nil,
			gen + "nameserver 1.1.1.1\nnameserver 2606:4700:4700::1111\n", true},
		{"lease in the server's order", &fwconfig.Resolver{DHCPInterface: "wan0"}, lease,
			gen + "nameserver 192.0.2.9\nnameserver 192.0.2.8\n", true},
		{"lease beats servers", &fwconfig.Resolver{DHCPInterface: "wan0", Servers: []string{"1.1.1.1"}}, lease,
			gen + "nameserver 192.0.2.9\nnameserver 192.0.2.8\n", true},
		{"no lease yet: servers", &fwconfig.Resolver{DHCPInterface: "wan0", Servers: []string{"1.1.1.1"}}, nil,
			gen + "nameserver 1.1.1.1\n", true},
		{"no lease, no servers: leave the file", &fwconfig.Resolver{DHCPInterface: "wan0"}, nil, "", false},
		{"at most three", &fwconfig.Resolver{DHCPInterface: "wan0"}, map[string][]string{"wan0": {"192.0.2.1", "192.0.2.2", "192.0.2.3", "192.0.2.4"}},
			gen + "nameserver 192.0.2.1\nnameserver 192.0.2.2\nnameserver 192.0.2.3\n", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got, ok := ResolvConf(&fwconfig.Instance{Resolver: tc.r}, tc.dhcp)
			if got != tc.want || ok != tc.ok {
				t.Errorf("ResolvConf = %q, %v; want %q, %v", got, ok, tc.want, tc.ok)
			}
		})
	}
}
