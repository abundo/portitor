// OpenVPNService is the OpenVPN auto rule's service, followed by the
// interface name.
const OpenVPNService = "openvpn"

// OpenVPNConf renders the openvpn.conf of one OpenVPN device (process) of
// an expanded document. The device is the agent's: it creates and
// addresses the tun device (ifconfig-noexec), and OpenVPN attaches to it.
// No script runs: the agent checks each client's user name and password
// through the management socket (management-client-auth), and clients are
// not asked for a certificate. The server's certificate is read from the
// agent's store (Paths.CertificateDir); the agent restarts OpenVPN when it
// is renewed. The file holds the tls-crypt key.
func OpenVPNConf(in *fwconfig.Instance, ifc *fwconfig.Interface, p Paths) string {
	o := ifc.OpenVPN
	f := p.Files(in)
	b := &strings.Builder{}
	b.WriteString("# Generated by portitor-agent. Do not edit.\n")
	fmt.Fprintf(b, "# OpenVPN server on %s (%s); portitor-agent checks the users' passwords.\n\n", ifc.Name, strings.ToUpper(o.Proto))
	fmt.Fprintf(b, "dev %s\ndev-type tun\n", ifc.Name)
	// IPv6 sockets take IPv4 clients too.
	if o.Proto == fwconfig.OpenVPNTCP {
		b.WriteString("proto tcp6-server\n")
	} else {
		b.WriteString("proto udp6\n")
	}
	fmt.Fprintf(b, "port %d\n", o.Port)
	b.WriteString("mode server\ntls-server\ntopology subnet\n")
	// The agent addresses the device; OpenVPN keeps it across restarts
	// of its own after dropping its privileges.
	b.WriteString("ifconfig-noexec\npersist-tun\npersist-key\n")
	// Data channel offload would make a device of its own.
	b.WriteString("disable-dco\n\n")

	for _, a := range ifc.Addresses {
		addr, err := netip.ParsePrefix(a)
		if err != nil {
			continue
		}
		pool := openVPNPoolOf(o, addr.Addr())
		first, last, ok := fwconfig.OpenVPNPool(pool, addr.Addr())
		if !ok {
			continue
		}
		if addr.Addr().Is4() {
			fmt.Fprintf(b, "ifconfig %s %s\n", addr.Addr(), mask4(addr.Bits()))
			fmt.Fprintf(b, "ifconfig-pool %s %s %s\n", first, last, mask4(pool.Bits()))
			fmt.Fprintf(b, "push \"route-gateway %s\"\n", addr.Addr())
		} else {
			// The remote is unused in a server; the pool's network address
			// is no client's.
			fmt.Fprintf(b, "ifconfig-ipv6 %s %s\n", addr, pool.Masked().Addr())
			fmt.Fprintf(b, "ifconfig-ipv6-pool %s/%d\n", first, pool.Bits())
		}
	}
	b.WriteString("push \"topology subnet\"\n")
	// A client of half a prefix reaches the rest (the server's address on
	// the other device, the other protocol's clients) through the tunnel.
	routes := []string{}
	for _, pfx := range o.Prefixes {
		if !slices.Contains(o.Pools, pfx) {
			routes = append(routes, pfx)
		}
	}
	routes = append(routes, o.Routes...)
	for _, r := range routes {
		pfx, err := netip.ParsePrefix(r)
		if err != nil {
			continue
		}
		pfx = pfx.Masked()
		if pfx.Addr().Is4() {
			fmt.Fprintf(b, "push \"route %s %s\"\n", pfx.Addr(), mask4(pfx.Bits()))
		} else {
			fmt.Fprintf(b, "push \"route-ipv6 %s\"\n", pfx)
		}
	}
	if o.RedirectGateway {
		if hasIPv6(ifc.Addresses) {
			b.WriteString("push \"redirect-gateway def1 ipv6 bypass-dhcp\"\n")
		} else {
			// No IPv6 in the tunnel: none outside it either.
			b.WriteString("push \"redirect-gateway def1 bypass-dhcp\"\npush \"block-ipv6\"\n")
		}
	}
	for _, d := range o.DNS {
		fmt.Fprintf(b, "push \"dhcp-option DNS %s\"\n", d)
	}
	if o.DNSDomain != "" {
		fmt.Fprintf(b, "push \"dhcp-option DOMAIN %s\"\n", strings.TrimSuffix(o.DNSDomain, "."))
	}
	if o.ClientToClient {
		b.WriteString("client-to-client\n")
	}
	b.WriteString("keepalive 10 60\n")
	if o.Proto == fwconfig.OpenVPNUDP {
		// Clients reconnect at once when the server restarts.
		b.WriteString("explicit-exit-notify 1\n")
	}

	// TLS: the server's certificate, no client certificates (OpenVPN
	// wants a CA all the same), ECDHE only.
	dir := p.CertificateDir(in.Name, o.Certificate)
	chain, key := filepath.Join(dir, acme.FullChainFile), filepath.Join(dir, acme.PrivKeyFile)
	fmt.Fprintf(b, "\nca %s\ncert %s\nkey %s\n", chain, chain, key)
	b.WriteString("dh none\ntls-version-min 1.2\ndata-ciphers AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305\n")
	b.WriteString("verify-client-cert none\nusername-as-common-name\n")
	// A renegotiation shows the token instead of asking the agent again.
	b.WriteString("auth-gen-token 0\n")
	fmt.Fprintf(b, "management %s unix\nmanagement-client-auth\n", f.OpenVPNSocket(o.Proto))
	b.WriteString("user nobody\ngroup nogroup\nverb 3\n")
	fmt.Fprintf(b, "\n<tls-crypt>\n%s</tls-crypt>\n", o.TLSCrypt)
	return b.String()
}

// openVPNPoolOf is the pool of the device's address addr.
func openVPNPoolOf(o *fwconfig.OpenVPN, addr netip.Addr) netip.Prefix {
	for _, s := range o.Pools {
		if q, err := netip.ParsePrefix(s); err == nil && q.Contains(addr) {
			return q
		}
	}
	return netip.Prefix{}
}

func mask4(bits int) string {
	return net.IP(net.CIDRMask(bits, 32)).String()
}

func hasIPv6(addrs []string) bool {
	for _, a := range addrs {
		if p, err := netip.ParsePrefix(a); err == nil && p.Addr().Is6() {
			return true
		}
	}
	return false
}

// openVPNAutoRule opens the OpenVPN server's port on its listen interface
// (any, when none), for the protocols it listens on.
func openVPNAutoRule(in *fwconfig.Instance) []AutoRule {
	ifc := in.OpenVPNServer()
	if ifc == nil || !ifc.Enabled {
		return nil
	}
	o := ifc.OpenVPN
	r := AutoRule{Service: OpenVPNService + " " + ifc.Name, Protocol: strings.Join(o.Protocols(), ","), DstPort: o.Port}
	if r.Protocol == "udp,tcp" {
		r.Protocol = "tcp,udp"
	}
	if o.Listen != "" {
		r.InInterfaces = []string{o.Listen}
	}
	return []AutoRule{r}
}

var tlsCryptBlock = regexp.MustCompile(`(?s)(<tls-crypt>\n).*?(</tls-crypt>)`)

// redactOpenVPN masks the tls-crypt key.
func redactOpenVPN(s string) string {
	return tlsCryptBlock.ReplaceAllString(s, "${1}<redacted>\n${2}")
}
