// writeISIS writes router isis, of the main table (vrf "") or a VRF: the
// same tag in each.
func writeISIS(b *strings.Builder, in *fwconfig.Instance, s *fwconfig.ISIS, vrf string) {
	fmt.Fprintf(b, "router isis %s%s\n", fwconfig.ISISTag, vrfSuffix(vrf))
	fmt.Fprintf(b, " net %s\n", s.NET)
	if s.Level != "" {
		fmt.Fprintf(b, " is-type %s\n", s.Level)
	}
	style := s.MetricStyle
	if style == "" {
		style = fwconfig.ISISMetricWide
	}
	fmt.Fprintf(b, " metric-style %s\n", style)
	if s.LogAdjacencyChanges {
		b.WriteString(" log-adjacency-changes\n")
	}
	if s.Overload {
		b.WriteString(" set-overload-bit\n")
	}
	if s.IPv6Topology {
		b.WriteString(" topology ipv6-unicast\n")
	}
	if s.AreaPassword != "" {
		fmt.Fprintf(b, " area-password %s %s\n", fwconfig.ISISAuthType(s.AreaPasswordType), s.AreaPassword)
	}
	if s.DomainPassword != "" {
		fmt.Fprintf(b, " domain-password %s %s\n", fwconfig.ISISAuthType(s.DomainPasswordType), s.DomainPassword)
	}
	for _, d := range s.DefaultOriginate {
		fmt.Fprintf(b, " default-information originate %s %s", d.Family, d.Level)
		if d.Always {
			b.WriteString(" always")
		}
		if d.Metric > 0 {
			fmt.Fprintf(b, " metric %d", d.Metric)
		}
		if d.RouteMap != "" {
			fmt.Fprintf(b, " route-map %s", d.RouteMap)
		}
		b.WriteString("\n")
	}
	for _, r := range s.Redistribute {
		for _, src := range frrSources(r.Source, r.Family, in.HasBFDRoutes()) {
			fmt.Fprintf(b, " redistribute %s %s %s", r.Family, src, r.Level)
			if r.Metric > 0 {
				fmt.Fprintf(b, " metric %d", r.Metric)
			}
			if r.RouteMap != "" {
				fmt.Fprintf(b, " route-map %s", r.RouteMap)
			}
			b.WriteString("\n")
		}
	}
	b.WriteString("exit\n!\n")
}

func setOf[T any](m map[string]T) map[string]bool {
	out := make(map[string]bool, len(m))
	for k := range m {
		out[k] = true
	}
	return out
}
