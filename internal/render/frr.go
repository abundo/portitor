// FRRDaemons renders FRR's daemons file: zebra and staticd (always on),
// bgpd, ospfd, ospf6d, isisd, vrrpd and bfdd as the instance runs them.
func FRRDaemons(in *fwconfig.Instance) string {
	b := &strings.Builder{}
	fmt.Fprintf(b, "# Generated by portitor-agent, instance %s. Do not edit.\n", in.Name)
	yes := func(on bool) string {
		if on {
			return "yes"
		}
		return "no"
	}
	fmt.Fprintf(b, "bgpd=%s\nospfd=%s\nospf6d=%s\nisisd=%s\nvrrpd=%s\nbfdd=%s\n", yes(in.BGPRunning()), yes(in.OSPFRunning(2)), yes(in.OSPFRunning(3)), yes(in.ISISRunning()), yes(in.VRRPRunning()), yes(in.BFDRunning()))
	b.WriteString("ripd=no\nripngd=no\npimd=no\npim6d=no\nldpd=no\nnhrpd=no\neigrpd=no\nbabeld=no\nsharpd=no\npbrd=no\nfabricd=no\npathd=no\n")
	b.WriteString("vtysh_enable=yes\n")
	b.WriteString("zebra_options=\"  -A 127.0.0.1 -s 90000000\"\n")
	b.WriteString("mgmtd_options=\"  -A 127.0.0.1\"\n")
	b.WriteString("bgpd_options=\"   -A 127.0.0.1\"\n")
	b.WriteString("ospfd_options=\"  -A 127.0.0.1\"\n")
	b.WriteString("ospf6d_options=\" -A ::1\"\n")
	b.WriteString("staticd_options=\"-A 127.0.0.1\"\n")
	if in.ISISRunning() {
		b.WriteString("isisd_options=\"   -A 127.0.0.1\"\n")
	}
	if in.BFDRunning() {
		b.WriteString("bfdd_options=\"   -A 127.0.0.1\"\n")
	}
	return b.String()
}

// FRRVtyshConf renders vtysh.conf: the integrated config (frr.conf), which
// frr-reload.py needs to reload.
func FRRVtyshConf(in *fwconfig.Instance) string {
	return fmt.Sprintf("! Generated by portitor-agent, instance %s. Do not edit.\nservice integrated-vtysh-config\n", in.Name)
}

// frrPasswordWord comes before a neighbour's password in frr.conf, and
// ospfKeyWord before an interface's OSPF MD5 key; Bundle.Redacted masks
// what follows them.
const (
	frrPasswordWord = " password "
	ospfKeyWord     = " md5 "
)

// FRRConf renders FRR's integrated config (frr.conf) for an instance's
// routing policy, BGP, OSPF, IS-IS, VRRP and BFD, of the main table and
// of each VRF (router ... vrf <name>). Static routes stay the agent's
// (kernel routes, proto 99): "redistribute static" is FRR's redistribute
// kernel; but a route with BFD is staticd's (writeBFDRoutes), so with
// those it is redistribute static as well. A VRF with an L3VNI gets its
// vni in its vrf block and the L2VPN EVPN address family in its router
// bgp, which is rendered from the main table's (l3vniBGP) when the VRF
// runs no BGP of its own.
func FRRConf(in *fwconfig.Instance) string {
	b := &strings.Builder{}
	fmt.Fprintf(b, "! Generated by portitor-agent, instance %s. Do not edit.\n", in.Name)
	b.WriteString("frr defaults traditional\n")
	b.WriteString("log syslog informational\n")
	b.WriteString("!\n")
	writeRoutingPolicy(b, &in.RoutingPolicy)
	writeBFD(b, in)
	writeVRFBlocks(b, in)
	writeInterfaces(b, in)
	for _, r := range in.Routings() {
		switch {
		case r.BGPOn():
			writeBGP(b, in, r.BGP, r.VRF, r.EVPN)
		case r.EVPN != nil && in.EVPNRunning():
			writeBGP(b, in, l3vniBGP(in, r.EVPN), r.VRF, r.EVPN)
		}
		for _, version := range []int{2, 3} {
			if o := r.OSPFOn(version); o != nil {
				writeOSPF(b, in, o, version, r.VRF)
			}
		}
		if r.ISISOn() {
			writeISIS(b, in, r.ISIS, r.VRF)
		}
	}
	b.WriteString("end\n")
	return b.String()
}

func writeRoutingPolicy(b *strings.Builder, rp *fwconfig.RoutingPolicy) {
	for _, pl := range rp.PrefixLists {
		kw := "ip"
		if pl.Family == "ipv6" {
			kw = "ipv6"
		}
		if pl.Description != "" {
			fmt.Fprintf(b, "%s prefix-list %s description %s\n", kw, pl.Name, pl.Description)
		}
		entries := slices.Clone(pl.Entries)
		sort.SliceStable(entries, func(i, j int) bool { return entries[i].Seq < entries[j].Seq })
		for _, e := range entries {
			fmt.Fprintf(b, "%s prefix-list %s seq %d %s %s", kw, pl.Name, e.Seq, e.Action, e.Prefix)
			if e.GE != 0 {
				fmt.Fprintf(b, " ge %d", e.GE)
			}
			if e.LE != 0 {
				fmt.Fprintf(b, " le %d", e.LE)
			}
			b.WriteString("\n")
		}
		if len(entries) == 0 {
			// An empty list must exist, and deny everything.
			fmt.Fprintf(b, "%s prefix-list %s seq 65535 deny any\n", kw, pl.Name)
		}
		b.WriteString("!\n")
	}
	for _, l := range rp.ASPathLists {
		for i, e := range l.Entries {
			fmt.Fprintf(b, "bgp as-path access-list %s seq %d %s %s\n", l.Name, (i+1)*5, e.Action, e.Regex)
		}
		if len(l.Entries) == 0 {
			fmt.Fprintf(b, "bgp as-path access-list %s seq 5 deny .*\n", l.Name)
		}
		b.WriteString("!\n")
	}
	for _, l := range rp.CommunityLists {
		kw, kind := "community-list", l.Kind
		if l.Large() {
			kw, kind = "large-community-list", strings.TrimPrefix(l.Kind, "large-")
		}
		for i, e := range l.Entries {
			fmt.Fprintf(b, "bgp %s %s %s seq %d %s %s\n", kw, kind, l.Name, (i+1)*5, e.Action, e.Value)
		}
		if len(l.Entries) == 0 {
			// An expanded list that matches nothing listed, as a list
			// can't be empty.
			fmt.Fprintf(b, "bgp %s expanded %s seq 5 deny .*\n", kw, l.Name)
		}
		b.WriteString("!\n")
	}
	families := map[string]string{}
	for _, pl := range rp.PrefixLists {
		families[pl.Name] = pl.Family
	}
	large := map[string]bool{}
	for _, l := range rp.CommunityLists {
		large[l.Name] = l.Large()
	}
	for _, m := range rp.RouteMaps {
		entries := slices.Clone(m.Entries)
		sort.SliceStable(entries, func(i, j int) bool { return entries[i].Seq < entries[j].Seq })
		if len(entries) == 0 {
			// A route map without entries denies everything.
			fmt.Fprintf(b, "route-map %s deny 65535\n", m.Name)
			if m.Description != "" {
				fmt.Fprintf(b, " description %s\n", m.Description)
			}
			b.WriteString("exit\n!\n")
		}
		for i, e := range entries {
			fmt.Fprintf(b, "route-map %s %s %d\n", m.Name, e.Action, e.Seq)
			desc := e.Description
			if desc == "" && i == 0 {
				desc = m.Description
			}
			if desc != "" {
				fmt.Fprintf(b, " description %s\n", desc)
			}
			ipKw := func(list string) string {
				if families[list] == "ipv6" {
					return "ipv6"
				}
				return "ip"
			}
			if e.MatchPrefixList != "" {
				fmt.Fprintf(b, " match %s address prefix-list %s\n", ipKw(e.MatchPrefixList), e.MatchPrefixList)
			}
			if e.MatchNextHop != "" {
				fmt.Fprintf(b, " match %s next-hop prefix-list %s\n", ipKw(e.MatchNextHop), e.MatchNextHop)
			}
			if e.MatchASPath != "" {
				fmt.Fprintf(b, " match as-path %s\n", e.MatchASPath)
			}
			if e.MatchCommunity != "" {
				if large[e.MatchCommunity] {
					fmt.Fprintf(b, " match large-community %s\n", e.MatchCommunity)
				} else {
					fmt.Fprintf(b, " match community %s\n", e.MatchCommunity)
				}
			}
			if e.MatchMetric != nil {
				fmt.Fprintf(b, " match metric %d\n", *e.MatchMetric)
			}
			if e.MatchTag != nil {
				fmt.Fprintf(b, " match tag %d\n", *e.MatchTag)
			}
			if e.SetLocalPreference != nil {
				fmt.Fprintf(b, " set local-preference %d\n", *e.SetLocalPreference)
			}
			if e.SetMetric != nil {
				fmt.Fprintf(b, " set metric %d\n", *e.SetMetric)
			}
			if e.SetWeight != nil {
				fmt.Fprintf(b, " set weight %d\n", *e.SetWeight)
			}
			if e.SetASPathPrepend != "" {
				fmt.Fprintf(b, " set as-path prepend %s\n", strings.Join(strings.Fields(e.SetASPathPrepend), " "))
			}
			if e.SetCommunity != "" {
				fmt.Fprintf(b, " set community %s", strings.Join(strings.Fields(e.SetCommunity), " "))
				if e.SetCommunityAdditive {
					b.WriteString(" additive")
				}
				b.WriteString("\n")
			}
			if e.SetLargeCommunity != "" {
				fmt.Fprintf(b, " set large-community %s\n", strings.Join(strings.Fields(e.SetLargeCommunity), " "))
			}
			if e.SetNextHop != "" {
				if a, err := netip.ParseAddr(e.SetNextHop); err == nil && a.Is6() {
					fmt.Fprintf(b, " set ipv6 next-hop global %s\n", a)
				} else {
					fmt.Fprintf(b, " set ip next-hop %s\n", e.SetNextHop)
				}
			}
			if e.SetOrigin != "" {
				fmt.Fprintf(b, " set origin %s\n", e.SetOrigin)
			}
			if e.OnMatchNext && e.Action == fwconfig.Permit {
				b.WriteString(" on-match next\n")
			}
			b.WriteString("exit\n!\n")
		}
	}
}

// writeBFD writes bfdd's profiles: one per interface with BFD.
func writeBFD(b *strings.Builder, in *fwconfig.Instance) {
	if !in.BFDRunning() {
		return
	}
	b.WriteString("bfd\n")
	for _, i := range in.BFD {
		fmt.Fprintf(b, " profile %s\n", fwconfig.BFDProfile(i.Name))
		if i.DetectMultiplier > 0 {
			fmt.Fprintf(b, "  detect-multiplier %d\n", i.DetectMultiplier)
		}
		if i.ReceiveInterval > 0 {
			fmt.Fprintf(b, "  receive-interval %d\n", i.ReceiveInterval)
		}
		if i.TransmitInterval > 0 {
			fmt.Fprintf(b, "  transmit-interval %d\n", i.TransmitInterval)
		}
		if i.Passive {
			b.WriteString("  passive-mode\n")
		}
		b.WriteString(" exit\n !\n")
	}
	b.WriteString("exit\n!\n")
}

// writeVRFBlocks writes the static routes with BFD, which staticd installs
// while the session to the gateway is up: the main table's, then each
// VRF's in its vrf block, with the VRF's L3VNI. The metric is FRR's
// distance.
func writeVRFBlocks(b *strings.Builder, in *fwconfig.Instance) {
	for _, vrf := range append([]string{""}, in.VRFNames()...) {
		lines := &strings.Builder{}
		indent := ""
		if vrf != "" {
			indent = " "
			if e := in.VRFByName(vrf).EVPN; e != nil {
				fmt.Fprintf(lines, " vni %d\n", e.VNI)
			}
		}
		for _, r := range in.Routes {
			iface := in.RouteBFD(r)
			if iface == "" || in.RouteVRF(r) != vrf {
				continue
			}
			kw := "ip"
			gw, _ := fwconfig.ParseAddr(r.Gateway)
			if gw.Is6() {
				kw = "ipv6"
			}
			fmt.Fprintf(lines, "%s%s route %s %s", indent, kw, fwconfig.BFDRouteDest(r), gw)
			if r.Interface != "" {
				fmt.Fprintf(lines, " %s", r.Interface)
			}
			if r.Metric > 0 {
				fmt.Fprintf(lines, " %d", r.Metric)
			}
			fmt.Fprintf(lines, " bfd profile %s\n", fwconfig.BFDProfile(iface))
		}
		switch {
		case lines.Len() == 0:
		case vrf == "":
			b.WriteString(lines.String() + "!\n")
		default:
			fmt.Fprintf(b, "vrf %s\n%sexit-vrf\n!\n", vrf, lines)
		}
	}
}

// vrfSuffix is what follows a router line in a VRF.
func vrfSuffix(vrf string) string {
	if vrf == "" {
		return ""
	}
	return " vrf " + vrf
}

// l3vniBGP is the BGP of a VRF with an L3VNI that runs none of its own: the
// main table's AS and router id, advertising the VRF's connected networks
// and static routes of the IP versions the L3VNI advertises.
func l3vniBGP(in *fwconfig.Instance, e *fwconfig.VRFEVPN) *fwconfig.BGP {
	g := &fwconfig.BGP{Enabled: true, ASN: in.BGP.ASN, RouterID: in.BGP.RouterID, LogNeighborChanges: true}
	for _, fam := range []struct {
		name string
		on   bool
	}{{"ipv4", e.AdvertiseIPv4}, {"ipv6", e.AdvertiseIPv6}} {
		if fam.on {
			g.Redistribute = append(g.Redistribute,
				fwconfig.BGPRedistribute{Family: fam.name, Source: fwconfig.RedistConnected},
				fwconfig.BGPRedistribute{Family: fam.name, Source: fwconfig.RedistStatic})
		}
	}
	return g
}

// writeBGP writes router bgp of the main table (vrf "") or a VRF, with the
// VRF's L3VNI (e, nil for none).
func writeBGP(b *strings.Builder, in *fwconfig.Instance, g *fwconfig.BGP, vrf string, e *fwconfig.VRFEVPN) {
	fmt.Fprintf(b, "router bgp %d%s\n", g.ASN, vrfSuffix(vrf))
	if g.RouterID != "" {
		fmt.Fprintf(b, " bgp router-id %s\n", g.RouterID)
	}
	if g.LogNeighborChanges {
		b.WriteString(" bgp log-neighbor-changes\n")
	} else {
		b.WriteString(" no bgp log-neighbor-changes\n")
	}
	if !g.EBGPRequiresPolicy {
		b.WriteString(" no bgp ebgp-requires-policy\n")
	}
	// Address families are activated per neighbour.
	b.WriteString(" no bgp default ipv4-unicast\n")
	if g.GracefulRestart {
		b.WriteString(" bgp graceful-restart\n")
	}
	if g.MultipathRelax {
		b.WriteString(" bgp bestpath as-path multipath-relax\n")
	}
	if g.Keepalive != 0 {
		fmt.Fprintf(b, " timers bgp %d %d\n", g.Keepalive, holdOf(g.Keepalive, g.Hold))
	}
	for _, p := range g.PeerGroups {
		fmt.Fprintf(b, " neighbor %s peer-group\n", p.Name)
		writePeer(b, p.Name, p, false)
	}
	for _, p := range g.Neighbors {
		ip := canonAddr(p.Address)
		if p.RemoteAS != "" {
			fmt.Fprintf(b, " neighbor %s remote-as %s\n", ip, p.RemoteAS)
		}
		if p.PeerGroup != "" {
			fmt.Fprintf(b, " neighbor %s peer-group %s\n", ip, p.PeerGroup)
		}
		// A link-local neighbour: on its interface, with IPv4 routes over
		// the IPv6 session (RFC 8950).
		if p.Interface != "" {
			fmt.Fprintf(b, " neighbor %s interface %s\n", ip, p.Interface)
			fmt.Fprintf(b, " neighbor %s capability extended-nexthop\n", ip)
		}
		writePeer(b, ip, p, true)
		// BFD is per neighbour, never on a peer group: only the members on
		// an interface with BFD get it.
		if iface := in.NeighborBFD(g, p); iface != "" {
			fmt.Fprintf(b, " neighbor %s bfd\n", ip)
			fmt.Fprintf(b, " neighbor %s bfd profile %s\n", ip, fwconfig.BFDProfile(iface))
		}
	}
	for _, fam := range []string{"ipv4", "ipv6"} {
		writeAddressFamily(b, g, fam, in.HasBFDRoutes())
	}
	writeEVPNFamily(b, g, e)
	b.WriteString("exit\n!\n")
}

// holdOf is the hold time for a keepalive: three times it when not set.
func holdOf(keepalive, hold int) int {
	if hold == 0 {
		return keepalive * 3
	}
	return hold
}

func canonAddr(s string) string {
	if a, err := fwconfig.ParseAddr(s); err == nil {
		return a.String()
	}
	return s
}

// writePeer writes a neighbour's or peer group's session settings. A peer
// group's remote-as comes after it is declared.
func writePeer(b *strings.Builder, id string, p fwconfig.BGPPeer, neighbor bool) {
	if !neighbor && p.RemoteAS != "" {
		fmt.Fprintf(b, " neighbor %s remote-as %s\n", id, p.RemoteAS)
	}
	if p.Description != "" {
		fmt.Fprintf(b, " neighbor %s description %s\n", id, p.Description)
	}
	if p.Password != "" {
		fmt.Fprintf(b, " neighbor %s%s%s\n", id, frrPasswordWord, p.Password)
	}
	if p.EBGPMultihop > 0 {
		fmt.Fprintf(b, " neighbor %s ebgp-multihop %d\n", id, p.EBGPMultihop)
	}
	if p.UpdateSource != "" {
		fmt.Fprintf(b, " neighbor %s update-source %s\n", id, canonAddr(p.UpdateSource))
	}
	if p.Passive {
		fmt.Fprintf(b, " neighbor %s passive\n", id)
	}
	if p.Keepalive != 0 {
		fmt.Fprintf(b, " neighbor %s timers %d %d\n", id, p.Keepalive, holdOf(p.Keepalive, p.Hold))
	}
	if p.Shutdown {
		fmt.Fprintf(b, " neighbor %s shutdown\n", id)
	}
}

func familyOf(prefix string) string {
	if pfx, err := netip.ParsePrefix(prefix); err == nil && pfx.Addr().Is6() {
		return "ipv6"
	}
	return "ipv4"
}

// writeAddressFamily writes a BGP address family; staticRoutes: FRR has
// static routes (with BFD) that redistribute static takes too.
func writeAddressFamily(b *strings.Builder, g *fwconfig.BGP, fam string, staticRoutes bool) {
	af := &strings.Builder{}
	for _, n := range g.Networks {
		if familyOf(n.Prefix) != fam {
			continue
		}
		fmt.Fprintf(af, "  network %s", n.Prefix)
		if n.RouteMap != "" {
			fmt.Fprintf(af, " route-map %s", n.RouteMap)
		}
		af.WriteString("\n")
	}
	for _, a := range g.Aggregates {
		if familyOf(a.Prefix) != fam {
			continue
		}
		fmt.Fprintf(af, "  aggregate-address %s", a.Prefix)
		if a.ASSet {
			af.WriteString(" as-set")
		}
		if a.SummaryOnly {
			af.WriteString(" summary-only")
		}
		af.WriteString("\n")
	}
	for _, r := range g.Redistribute {
		if r.Family != fam {
			continue
		}
		for _, src := range frrSources(r.Source, fam, staticRoutes) {
			fmt.Fprintf(af, "  redistribute %s", src)
			if r.RouteMap != "" {
				fmt.Fprintf(af, " route-map %s", r.RouteMap)
			}
			af.WriteString("\n")
		}
	}
	if g.MaximumPaths > 0 {
		fmt.Fprintf(af, "  maximum-paths %d\n", g.MaximumPaths)
	}
	for _, p := range g.PeerGroups {
		writePeerFamily(af, p.Name, p, fam)
	}
	for _, p := range g.Neighbors {
		writePeerFamily(af, canonAddr(p.Address), p, fam)
	}
	if af.Len() == 0 {
		return
	}
	fmt.Fprintf(b, " !\n address-family %s unicast\n", fam)
	b.WriteString(af.String())
	b.WriteString(" exit-address-family\n")
}

// writeEVPNFamily writes the L2VPN EVPN address family: the peers that
// activate it and, with EVPN on, the VNIs of the vxlan devices zebra finds
// as bridge members; in a VRF with an L3VNI (e), its type-5 routes, route
// distinguisher and route targets.
func writeEVPNFamily(b *strings.Builder, g *fwconfig.BGP, e *fwconfig.VRFEVPN) {
	af := &strings.Builder{}
	for _, p := range g.PeerGroups {
		writePeerEVPN(af, p.Name, p.EVPN)
	}
	for _, p := range g.Neighbors {
		writePeerEVPN(af, canonAddr(p.Address), p.EVPN)
	}
	if g.EVPN {
		af.WriteString("  advertise-all-vni\n")
	}
	if e != nil {
		if e.AdvertiseIPv4 {
			af.WriteString("  advertise ipv4 unicast\n")
		}
		if e.AdvertiseIPv6 {
			af.WriteString("  advertise ipv6 unicast\n")
		}
		if e.RD != "" {
			fmt.Fprintf(af, "  rd %s\n", e.RD)
		}
		auto := autoRT(g.ASN, e.VNI)
		for _, rt := range frrRTs(e.ImportRTs, auto) {
			fmt.Fprintf(af, "  route-target import %s\n", rt)
		}
		for _, rt := range frrRTs(e.ExportRTs, auto) {
			fmt.Fprintf(af, "  route-target export %s\n", rt)
		}
	}
	if af.Len() == 0 {
		return
	}
	b.WriteString(" !\n address-family l2vpn evpn\n")
	b.WriteString(af.String())
	b.WriteString(" exit-address-family\n")
}

// autoRT is the route target FRR derives for an L3VNI: AS:VNI, the VNI's
// low 16 bits with a 4-byte AS.
func autoRT(asn, vni uint32) string {
	if asn > 65535 {
		vni &= 0xffff
	}
	return fmt.Sprintf("%d:%d", asn, vni)
}

// frrRTs orders route targets for FRR, which refuses one that is in the
// VRF's list already, as the derived one (auto) is until the first
// configured one replaces it: that one goes last, and alone it is left out,
// the derived one being the same.
func frrRTs(rts []string, auto string) []string {
	if !slices.Contains(rts, auto) {
		return rts
	}
	out := slices.DeleteFunc(slices.Clone(rts), func(rt string) bool { return rt == auto })
	if len(out) == 0 {
		return nil
	}
	return append(out, auto)
}

func writePeerEVPN(b *strings.Builder, id string, s fwconfig.BGPEVPNFamily) {
	if !s.Activate {
		return
	}
	fmt.Fprintf(b, "  neighbor %s activate\n", id)
	if s.RouteReflectorClient {
		fmt.Fprintf(b, "  neighbor %s route-reflector-client\n", id)
	}
}

// frrSource is FRR's name of a redistribute source in an IP version.
func frrSource(src, fam string) string {
	switch src {
	case fwconfig.RedistStatic:
		return "kernel"
	case fwconfig.RedistOSPF:
		if fam == "ipv6" {
			return "ospf6"
		}
	}
	return src
}

// frrSources are FRR's sources of a redistribute source: static routes
// are the kernel's, and staticd's too when it has some (BFD).
func frrSources(src, fam string, staticRoutes bool) []string {
	if src == fwconfig.RedistStatic && staticRoutes {
		return []string{"kernel", "static"}
	}
	return []string{frrSource(src, fam)}
}

