package render

import (
	"fmt"
	"strings"
)

// EarlyTable is the host's boot-time policy (`portitor-agent early`,
// portitor-early.service, loaded before the network is up): it closes the
// host until the agent has loaded the default instance's ruleset, which
// then deletes it (EarlyDelete). It is separate from the `inet firewall`
// table, and a drop in either is final, so the two may overlap.
const EarlyTable = "portitor_early"

// Early renders the boot-time policy from the agent's own configuration
// alone (no document): input drops all but loopback, established and
// related, essential ICMP and neighbour discovery, the DHCP clients'
// replies and the anti-lockout rule (lockout, nil for none); forward drops
// everything. Output is left open, so the DHCP clients and the HA
// heartbeats can go out. It replaces the table if there is one.
func Early(lockout *AntiLockout) string {
	b := &strings.Builder{}
	b.WriteString("# Generated by portitor-agent: the boot-time policy. Do not edit.\n")
	fmt.Fprintf(b, "table inet %s\ndelete table inet %s\n\n", EarlyTable, EarlyTable)
	fmt.Fprintf(b, "table inet %s {\n", EarlyTable)
	b.WriteString("\tchain input {\n")
	b.WriteString("\t\ttype filter hook input priority filter; policy drop;\n")
	b.WriteString("\t\tct state established,related accept\n")
	b.WriteString("\t\tiif \"lo\" accept\n")
	b.WriteString("\t\tmeta l4proto ipv6-icmp icmpv6 type { nd-router-solicit, nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert, destination-unreachable, packet-too-big, time-exceeded, parameter-problem } accept\n")
	b.WriteString("\t\tmeta l4proto icmp icmp type { destination-unreachable, time-exceeded, parameter-problem } accept\n")
	// A DHCP server's answer to a broadcast is no reply to conntrack.
	b.WriteString("\t\tudp sport 67 udp dport 68 accept\n")
	b.WriteString("\t\tip6 saddr fe80::/10 udp sport 547 udp dport 546 accept\n")
	if lockout != nil {
		if dport := portsMatch(lockout.Ports()); dport != "" {
			v4, v6 := splitFamilies(lockout.AllowFrom)
			for _, m := range []struct {
				key   string
				addrs []string
			}{{"ip", v4}, {"ip6", v6}} {
				if len(m.addrs) > 0 {
					fmt.Fprintf(b, "\t\t%s saddr %s tcp dport %s accept comment %q\n", m.key, set(m.addrs), dport, AntiLockoutService)
				}
			}
		}
	}
	b.WriteString("\t}\n\n")
	b.WriteString("\tchain forward {\n")
	b.WriteString("\t\ttype filter hook forward priority filter; policy drop;\n")
	b.WriteString("\t}\n")
	b.WriteString("}\n")
	return b.String()
}

// EarlyDelete removes the boot-time policy, as one nft transaction that
// succeeds whether it is there or not.
func EarlyDelete() string {
	return fmt.Sprintf("table inet %s\ndelete table inet %s\n", EarlyTable, EarlyTable)
}
