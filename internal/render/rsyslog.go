package render

import (
	"fmt"
	"net/netip"
	"slices"
	"strings"

	"github.com/abundo/portitor/internal/fwconfig"
)

// SyslogService is the syslog servers' auto output rule's service.
const SyslogService = "syslog"

// RsyslogConf renders rsyslog.conf for the default instance's syslog
// servers. It replaces the distribution's whole config: rsyslog reads the
// journal (imjournal; journald keeps the host's logs) and only forwards,
// writing no files of its own. Each server has its own queue, so one that
// is down holds up neither the others nor the journal; a TCP server's
// messages wait in it and are sent when the server is back, a UDP
// server's are lost while it is down.
func RsyslogConf(in *fwconfig.Instance) string {
	b := &strings.Builder{}
	b.WriteString("# Generated by portitor-agent. Do not edit.\n\n")
	b.WriteString("global(workDirectory=\"/var/spool/rsyslog\")\n")
	// No earlier entries on the first start: only what is logged from now.
	b.WriteString("module(load=\"imjournal\" StateFile=\"imjournal.state\" IgnorePreviousMessages=\"on\")\n")
	for _, s := range in.Syslog.Servers {
		template := "RSYSLOG_TraditionalForwardFormat"
		if s.Format == "rfc5424" {
			template = "RSYSLOG_SyslogProtocol23Format"
		}
		fmt.Fprintf(b, "\n# %s %s port %d, %s and more urgent\n", s.Protocol, s.Address, s.Port, s.Severity)
		fmt.Fprintf(b, "if $syslogseverity <= %d then {\n", slices.Index(fwconfig.SyslogSeverities, s.Severity))
		fmt.Fprintf(b, "\taction(type=\"omfwd\" target=\"%s\" port=\"%d\" protocol=\"%s\" template=\"%s\"", s.Address, s.Port, s.Protocol, template)
		if s.Protocol == "tcp" && s.Format == "rfc5424" {
			// RFC 6587's octet counting, which RFC 5424 receivers expect.
			b.WriteString(" TCP_Framing=\"octet-counted\"")
		}
		b.WriteString("\n\t\tqueue.type=\"LinkedList\" queue.size=\"10000\" action.resumeRetryCount=\"-1\" action.resumeInterval=\"10\")\n}\n")
	}
	return b.String()
}

// syslogOutputRules are the output chain's accepts of what rsyslog sends
// to the syslog servers.
func syslogOutputRules(in *fwconfig.Instance) []string {
	if in.Syslog == nil || !in.Default {
		return nil
	}
	var out []string
	for _, s := range in.Syslog.Servers {
		a, err := netip.ParseAddr(s.Address)
		if err != nil {
			continue
		}
		fam := "ip"
		if a.Unmap().Is6() {
			fam = "ip6"
		}
		out = append(out, fmt.Sprintf("%s daddr %s %s dport %d accept %s", fam, a.Unmap(), s.Protocol, s.Port, comment("auto", SyslogService)))
	}
	return slices.Compact(out)
}
