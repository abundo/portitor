// ConntrackSyncService is the auto rule letting the HA peer's conntrackd
// in, from the ConntrackSyncSet set.
const (
	ConntrackSyncService = "conntrack sync"
	ConntrackSyncSet     = "conntrack_sync"
)

// HAConfigService is the auto rule letting the HA peer's portitor-config
// reach this host's (fwconfig.HAConfigAccess), from the HAConfigSet set.
const (
	HAConfigService = "portitor-config peer"
	HAConfigSet     = "portitor_config_peer"
)

// HAAgentService is the auto rule letting the HA peer's agent reach this
// host's for the heartbeat, from the HAAgentSet set.
const (
	HAAgentService = "portitor-agent peer"
	HAAgentSet     = "portitor_agent_peer"
	// HAAgentLinkSet is the source set of the same rule on the HA link,
	// from the peer's link-local address.
	HAAgentLinkSet = "portitor_agent_peer_link"
)

// haOutputRules are the output chain's accepts of what this host sends its
// HA peer: heartbeats and the copy of the configuration. A rule closing the
// output chain must not split the pair.
func haOutputRules(in *fwconfig.Instance) []string {
	h := in.HAConfig
	if h == nil {
		return nil
	}
	var out []string
	for _, s := range h.From {
		a, err := netip.ParseAddr(s)
		if err != nil {
			continue
		}
		fam := "ip"
		if a.Is6() {
			fam = "ip6"
		}
		for _, port := range []int{h.AgentPort, h.Port} {
			if port != 0 {
				out = append(out, fmt.Sprintf("%s daddr %s tcp dport %d accept %s", fam, a, port, comment("auto", HAAgentService)))
			}
		}
	}
	if h.Link != "" && h.AgentPort != 0 {
		out = append(out, fmt.Sprintf("oifname %s ip6 daddr %s tcp dport %d accept %s", quotedSet([]string{h.Link}), h.LinkPeer, h.AgentPort, comment("auto", HAAgentService)))
	}
	return slices.Compact(out)
}

// ConntrackdConf renders conntrackd.conf for an instance on an HA pair
// (fwconfig.ConntrackSync): FTFW over UDP to the peer's link-local
// address on the HA link (Interface, which link-local needs), and the peer's
// connections straight into the kernel's table (no external cache), so
// nothing has to commit them when the host takes over. The firewall's own
// connections are left out. A virtual firewall's lock file and control
// socket are in its unit's private /tmp; the default instance's in the
// distribution's places.
func ConntrackdConf(in *fwconfig.Instance) string {
	c := in.ConntrackSync
	lock, ctl := "/tmp/conntrackd.lock", "/tmp/conntrackd.ctl"
	if in.Default {
		lock, ctl = "/var/lock/conntrackd.lock", "/var/run/conntrackd.ctl"
	}
	b := &strings.Builder{}
	fmt.Fprintf(b, "# Generated by portitor-agent, instance %s. Do not edit.\n", in.Name)
	fmt.Fprintf(b, `Sync {
	Mode FTFW {
		DisableExternalCache On
	}
	UDP {
		IPv6_address %s
		IPv6_Destination_Address %s
		Port %d
		Interface %s
		SndSocketBuffer 1249280
		RcvSocketBuffer 1249280
		Checksum on
	}
}
General {
	HashSize 32768
	HashLimit 131072
	LogFile off
	Syslog on
	LockFile %s
	UNIX {
		Path %s
	}
	NetlinkBufferSize 2097152
	NetlinkBufferSizeMaxGrowth 8388608
	Filter From Userspace {
		Address Ignore {
			IPv4_address 127.0.0.1
			IPv6_address ::1
			IPv6_address %s
			IPv6_address %s
		}
	}
}
`, c.This, c.Peer, fwconfig.ConntrackSyncPort, c.Interface, lock, ctl, c.This, c.Peer)
	return b.String()
}
