package render

import (
	"strings"

	"github.com/abundo/portitor/internal/fwconfig"
)

// ResolvConf renders the host's /etc/resolv.conf (fwconfig.Resolver): the
// DNS servers of the lease on the resolver's DHCP interface, in the
// server's order, else its own servers. ok is false when the instance has
// no resolver or there is nothing to put in the file yet (no lease, no
// servers): an empty file would leave the host without DNS, so the
// agent leaves the one there.
//
// dhcpDNS is the instance's learned DNS servers by interface. They are
// volatile like any lease, so the file is written outside an apply too
// (Agent.onDHCPChange).
func ResolvConf(in *fwconfig.Instance, dhcpDNS map[string][]string) (conf string, ok bool) {
	r := in.Resolver
	if r == nil {
		return "", false
	}
	servers := dhcpDNS[r.DHCPInterface]
	if r.DHCPInterface == "" || len(servers) == 0 {
		servers = r.Servers
	}
	if len(servers) > fwconfig.MaxResolverServers {
		servers = servers[:fwconfig.MaxResolverServers]
	}
	if len(servers) == 0 {
		return "", false
	}
	b := &strings.Builder{}
	b.WriteString("# Generated by portitor-agent. Do not edit.\n")
	for _, s := range servers {
		b.WriteString("nameserver " + s + "\n")
	}
	return b.String(), true
}
