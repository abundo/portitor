package agent

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/abundo/portitor/internal/fwconfig"
)

// The host's resolver follows the lease: a lease with DNS servers rewrites
// resolv.conf (replacing the installer's, which is kept), one without
// leaves it alone.
func TestResolverFollowsLease(t *testing.T) {
	dir := t.TempDir()
	a, _ := testAgent(t)
	a.cfg.DryRun = false
	a.cfg.Paths.ResolvConf = filepath.Join(dir, "resolv.conf")
	installer := "nameserver 1.1.1.1\n"
	if err := os.WriteFile(a.cfg.Paths.ResolvConf, []byte(installer), 0o644); err != nil {
		t.Fatal(err)
	}
	doc := fwconfig.SampleDocument()
	in := &doc.Instances[0]
	in.Default = true
	wan := &in.Interfaces[0]
	wan.IPv4Mode, wan.Addresses = fwconfig.ModeDHCP, nil
	in.Resolver = &fwconfig.Resolver{DHCPInterface: wan.Name}
	a.mu.Lock()
	a.applied = &doc
	a.mu.Unlock()

	read := func() string {
		b, err := os.ReadFile(a.cfg.Paths.ResolvConf)
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}

	// No lease yet, no servers: nothing to write.
	a.onDHCPChange(in.Name)
	if got := read(); got != installer {
		t.Fatalf("resolv.conf without a lease: %q", got)
	}

	a.dhcp.mu.Lock()
	a.dhcp.leases[dhcpKey{instance: in.Name, iface: wan.Name}] = &Lease{DNS: []string{"192.0.2.9", "192.0.2.8"}}
	a.dhcp.mu.Unlock()
	a.onDHCPChange(in.Name)
	if got, want := read(), "# Generated by portitor-agent. Do not edit.\nnameserver 192.0.2.9\nnameserver 192.0.2.8\n"; got != want {
		t.Errorf("resolv.conf = %q, want %q", got, want)
	}
	if b, err := os.ReadFile(a.cfg.Paths.ResolvConf + ".portitor-orig"); err != nil || string(b) != installer {
		t.Errorf("the installer's file is kept: %q, %v", b, err)
	}
}
