# Runs in the installed system (chroot) at the end of the installation:
# installs the packages from the repository on the ISO (no network), Portitor
# from the release archive on the ISO, and prepares the first-boot setup
# (portitor-setup.py).
set -eu
d=/tmp/portitor-iso

# The packages (packages.txt) from the ISO's repository alone: its apt source
# is the only one, and what it holds is complete (iso/build.sh resolves it as
# for an empty system). Not signed: it is the installer's own medium.
echo "deb [trusted=yes] file:$d/repo ./" >"$d/offline.list"
apt_iso() {
	DEBIAN_FRONTEND=noninteractive apt-get -q -o Dir::Etc::sourcelist="$d/offline.list" \
		-o Dir::Etc::sourceparts=- -o APT::Get::List-Cleanup=0 "$@"
}
# What d-i's preseed answers for these (the installer's debconf is not this one's).
debconf-set-selections <<'DEBCONF'
wireshark-common wireshark-common/install-setuid boolean false
iperf3 iperf3/start_daemon boolean false
DEBCONF
apt_iso update
# shellcheck disable=SC2046
apt_iso install -y --no-install-recommends $(sed 's/#.*//' "$d/packages.txt")
rm -rf /var/lib/apt/lists/*

# The package sources for later: Debian's, and ISC's BIND repository (as
# install.py adds it; written here so that it finds it and does not call apt).
# Nothing is fetched now.
mkdir -p "$d/release"
tar -xzf "$d/portitor.tar.gz" -C "$d/release"
root=$(dirname "$(find "$d/release" -maxdepth 2 -name install.py | head -n 1)")
install -m 0644 "$root/deploy/apt/isc-bind.asc" /usr/share/keyrings/isc-bind.asc
echo "deb [signed-by=/usr/share/keyrings/isc-bind.asc] https://bind.debian.net/bind trixie main" \
	>/etc/apt/sources.list.d/isc-bind.list
cat >/etc/apt/sources.list <<'SOURCES'
# The installation used the ISO alone. Debian 13's mirrors, for updates.
deb http://deb.debian.org/debian trixie main non-free-firmware
deb http://deb.debian.org/debian trixie-updates main non-free-firmware
deb http://deb.debian.org/debian-security trixie-security main non-free-firmware
SOURCES

# Binaries, units, example configs and /usr/lib/portitor/install.py.
# Nothing is started; portitor-setup configures and starts both.
python3 "$root/install.py" --local "$root" --manager --agent --yes

# In a VM the host owns the CPU microcode; the installer adds it by CPU vendor
# regardless. Purged before update-grub so no microcode initrd stays listed.
if grep -qw hypervisor /proc/cpuinfo; then
    apt-get purge -y intel-microcode amd64-microcode 2>/dev/null || true
fi

# In PATH, next to the binaries: run again, it changes the LAN and WAN.
install -D -m 0755 "$d/portitor-setup.py" /usr/bin/portitor-setup
install -D -m 0644 "$d/portitor-setup.bash" /usr/share/bash-completion/completions/portitor-setup
install -D -m 0644 "$d/portitor-firstboot.service" /etc/systemd/system/portitor-firstboot.service
systemctl enable portitor-firstboot.service
# Password recovery: a GRUB entry that boots into portitor-recover (no root
# login exists). The unit is not enabled; the entry starts it.
install -D -m 0755 "$d/portitor-recover.sh" /usr/sbin/portitor-recover
install -D -m 0644 "$d/portitor-recovery.service" /etc/systemd/system/portitor-recovery.service
install -D -m 0755 "$d/42_portitor_recovery" /etc/grub.d/42_portitor_recovery
# Debian's "(recovery mode)" entries boot rescue.target, which asks for root's
# password: locked here, so they end at "the root account is locked". Ours
# takes their place.
mkdir -p /etc/default/grub.d
cat >/etc/default/grub.d/portitor-recovery.cfg <<'GRUB'
# Generated by Portitor's installer: no Debian recovery mode entries (root has
# no password); use "Portitor password recovery".
GRUB_DISABLE_RECOVERY=true
GRUB
# The interfaces and their addresses on the login screen.
install -D -m 0755 "$d/portitor-issue.sh" /usr/sbin/portitor-issue
install -D -m 0644 "$d/portitor-issue.service" /etc/systemd/system/portitor-issue.service
systemctl enable portitor-issue.service
# A serial console beside the screen: the GRUB menu, the kernel's messages and
# a login on ttyS0 (systemd's getty generator starts one for a console= on a
# serial port). tty0 is named last, so /dev/console, and the first-boot setup
# and password recovery, stay on the screen.
mkdir -p /etc/default/grub.d
cat >/etc/default/grub.d/portitor-serial.cfg <<'GRUB'
# Generated by Portitor's installer: serial console on ttyS0.
GRUB_CMDLINE_LINUX="$GRUB_CMDLINE_LINUX console=ttyS0,115200n8 console=tty0"
GRUB_TERMINAL="console serial"
GRUB_SERIAL_COMMAND="serial --unit=0 --speed=115200"
GRUB
update-grub
# SSH is open from the LAN (the portitor-mgmt service).
systemctl enable ssh.service
# Only in an ISO built with --test: answers, so the setup asks nothing.
if [ -f "$d/firstboot.answers" ]; then
	install -m 0600 "$d/firstboot.answers" /etc/portitor/firstboot.answers
fi

# The agent runs BIND and FRR: the default virtual firewall's under these
# units, which it unmasks when it uses them, the others' under portitor-*@
# units (and every instance's DHCP server and router advertisements under
# portitor-dhcpd@).
# rsyslog runs only to send the journal to syslog servers.
systemctl mask named.service frr.service \
	conntrackd.service rsyslog.service

# The agent owns the interfaces: nothing else may configure them (a second
# DHCP client on the WAN keeps the agent from getting a lease).
cat >/etc/network/interfaces <<'IFACES'
# The Portitor agent configures every other interface.
auto lo
iface lo inet loopback
IFACES

# Conntrack timestamps (the Connections page's start times) in every
# namespace: new namespaces take the module's default, not the root's sysctl.
echo 'options nf_conntrack tstamp=1' >/etc/modprobe.d/portitor-conntrack.conf

# Keep the journal (update jobs are read from it) across reboots.
mkdir -p /var/log/journal
